-- ─── Remove anon access from already-applied policies ───────────────────────
-- api_keys / user_devices were originally created with `for all to anon,
-- authenticated`. The `anon` role must never reach user-owned rows.

drop policy if exists "Users can manage own API keys" on public.api_keys;
